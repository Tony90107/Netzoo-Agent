"""count-answers live F1/F2 (ROUND.md) from live/. No model call.

F1 (hard): no "meets" run ends refused for the count (a count_answer DECLINE, or any refusal line about the sample
minimum). F2 (target): >= 6 of the 8 "below" runs end DECLINE with the minimum-samples contract line (count_answer)
or with today's count refusal (a line naming the sample minimum).

Usage: python3 score_live.py      (LIVE.md)
"""
from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
MINIMUM = re.compile(r"at least (three|3) samples|needs at least \d+ samples", re.I)


def core_of(turn: Path) -> dict | None:
    core = None
    for trace in sorted(turn.glob("trace-*.jsonl")):
        for line in trace.read_text().splitlines():
            if '"core.decision"' in line and (row := json.loads(line)).get("event_type") == "core.decision":
                core = row["payload"]
    return core


def main():
    rows = []
    for folder in sorted((HERE / "live").glob("ca-*")):
        job = json.loads((folder / "job.json").read_text())
        turns = sorted(folder.glob("t[0-9]"))
        cores = [core_of(t) for t in turns]
        end = next((c for c in reversed(cores) if c), None) or {}
        lines = " ".join(part.get("line", "") for part in end.get("declined") or [])
        count_refusal = end.get("kind") == "DECLINE" and (end.get("basis") == "count_answer" or bool(MINIMUM.search(lines)))
        asked = [(c or {}).get("facts", [{}])[0].get("question", "") if (c or {}).get("kind") == "ASK" else "" for c in cores]
        rows.append({**job, "end_kind": end.get("kind"), "end_basis": end.get("basis"), "count_refusal": count_refusal,
                     "asked": asked, "line": lines[:300], "clicks": len(job["sent"]) - 1})
    meets = [r for r in rows if r["mode"] == "meets"]
    below = [r for r in rows if r["mode"] == "below"]
    f1 = [r for r in meets if r["count_refusal"]]
    f2 = sum(r["count_refusal"] for r in below)
    out = ["# count-answers live (generated by score_live.py; do not edit)", "",
           f"- F1 (hard) meets runs refused for the count: {len(f1)} {[r['session'] for r in f1]}: "
           f"{'pass' if not f1 else 'FAIL'}",
           f"- F2 (target) below runs ending in the count refusal: {f2}/{len(below)} (>= 6): "
           f"{'pass' if f2 >= 6 else 'FAIL'}", ""]
    for r in rows:
        out.append(f"- {r['session']} {r['mode']}: clicks {r['clicks']} sent {r['sent'][1:]} -> {r['end_kind']}/"
                   f"{r['end_basis']} count refusal {r['count_refusal']} | asked {[a[:70] for a in r['asked'] if a]}"
                   + (f"\n    {r['line']}" if r["line"] else ""))
    (HERE / "LIVE.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
