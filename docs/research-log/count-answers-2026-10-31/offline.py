"""count-answers E1 (ROUND.md): every recorded answer turn of the current-system runs (j1-j8, j9 r1-r3, j10 arm M
r1-r3) where the task state the app kept holds an agent yes/no answer bound that turn: the rule run on the recorded
call with that state. "yes" must change nothing; every "no" is listed with its gold. Pure code, no model call.

The saved state is after the turn; an answer bound on the turn carries `turn` = the turns count at binding, one less
than the saved count, so the state as the step saw it is the saved one with `turns` set back by one.

Usage: python3 offline.py      (E1.md, e1.json)
"""
from __future__ import annotations

import glob
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "scripts"))
from netzoo_agent_core.contracts.core_decision import CoreDecision  # noqa: E402
from netzoo_agent_core.graph.count_answer_call import answered_count_question, counted_core  # noqa: E402

CT = Path("/Users/chenzhonghan/Documents/LLM AGENT/.worktrees/netzoo-ct/docs/research-log")
RR = Path("/Users/chenzhonghan/Documents/LLM AGENT/.worktrees/netzoo-rr/docs/research-log")
RUNS = {"j1": "jev-guard-2026-10-27/live/j1", "j2": "jev-guard-2026-10-27/live/j2g", "j3": "jev-j3-2026-10-27/live/j3g",
        "j4": "jev-j4-2026-10-27/live/j4g", "j5": "jev-j5-2026-10-28/live/j5a", "j6": "jev-j6-2026-10-29/live/j6a",
        "j7": "jev-links-first-2026-10-29/live/j7off", "j8": "j8-paired-2026-10-29/live/j8new",
        "j9r1": "hybrid-j9-2026-10-31/live/h9r1", "j9r2": "hybrid-j9-2026-10-31/live/h9r2",
        "j9r3": "hybrid-j9-2026-10-31/live/h9r3"}
FOLDERS = {**{k: CT / v for k, v in RUNS.items()},
           **{f"j10r{r}": RR / f"fresh-j10-2026-10-31/live/m{r}" for r in (1, 2, 3)}}
SETS = [CT / s / "items.json" for s in ("jev-guard-2026-10-27/j1", "jev-guard-2026-10-27/j2", "jev-j3-2026-10-27/j3",
                                        "jev-j4-2026-10-27/j4", "jev-j5-2026-10-28/j5", "jev-j6-2026-10-29/j6",
                                        "jev-links-first-2026-10-29/j7", "j8-paired-2026-10-29/j8",
                                        "hybrid-j9-2026-10-31/j9")] + [RR / "fresh-j10-2026-10-31/j10/items.json"]


def core_of(turn: Path) -> dict | None:
    core = None
    for trace in sorted(turn.glob("trace-*.jsonl")):
        for line in trace.read_text().splitlines():
            if '"core.decision"' in line and (row := json.loads(line)).get("event_type") == "core.decision":
                core = row["payload"]
    return core


def main():
    gold = {i["id"]: i for path in SETS for i in json.loads(path.read_text())["single"]}
    rows = []
    for run, folder in FOLDERS.items():
        for session in sorted(glob.glob(str(folder / "hb-*-1"))):
            item = gold[re.search(r"-([A-Z]\d+)-1$", session).group(1)]
            sent = json.loads(Path(session, "job.json").read_text()).get("sent", [])
            for turn in sorted(Path(session).glob("t[0-9]"))[1:]:
                saved = json.loads((turn / "session.json").read_text()).get("task_state") if (turn / "session.json").exists() else None
                core = core_of(turn)
                if not saved or not core:
                    continue
                state = {**saved, "turns": saved.get("turns", 0) - 1}
                question = answered_count_question(state)
                if question is None:
                    continue
                model = CoreDecision.model_validate({k: v for k, v in core.items() if k in CoreDecision.model_fields})
                after, action = counted_core(model, question)
                g = item["final_after_fact"]["call"] if "fact" in sent and item.get("final_after_fact") else item["expected_call"]
                rows.append({"run": run, "id": item["id"], "turn": turn.name, "value": question["value"],
                             "question": question["question"], "workflow": question["workflow"], "action": action,
                             "before": core["kind"], "after": after.kind, "gold": g,
                             "line": after.declined[0].line if after.kind == "DECLINE" and after is not model else ""})
    (HERE / "e1.json").write_text(json.dumps(rows, indent=1))
    yes_changed = [r for r in rows if r["value"] == "yes" and r["action"] not in ("answer_yes", "not_do")]
    bad = [r for r in rows if r["value"] == "no" and r["after"] == "DECLINE" and r["before"] != "DECLINE"
           and r["gold"] in ("DO", "PARTIAL")]
    lines = ["# E1 (generated by offline.py; do not edit)", "",
             f"- in-scope answer turns {len(rows)}: yes {sum(r['value'] == 'yes' for r in rows)}, "
             f"no {sum(r['value'] == 'no' for r in rows)}",
             f"- E1 yes answers changed: {len(yes_changed)} (0); 'no' turned a gold-DO end into a refusal: {len(bad)} (0): "
             f"{'pass' if not yes_changed and not bad else 'FAIL'}", "", "Every in-scope answer turn:"]
    lines += [f"- {r['run']} {r['id']} {r['turn']} answered {r['value']} to \"{r['question']}\" ({r['workflow']}): "
              f"{r['before']} -> {r['after']} [{r['action']}] gold {r['gold']}" + (f"\n    {r['line']}" if r["line"] else "")
              for r in rows]
    (HERE / "E1.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
