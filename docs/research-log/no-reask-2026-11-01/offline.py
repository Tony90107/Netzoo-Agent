"""no-reask N1 (ROUND.md): every recorded later turn's fact-agent questions (the `core.fact_check` event: accepted and
queued) against the task state the app kept after that turn (its known facts include the answers bound on the turn);
every question the rule blocks is listed with the answer that blocks it, for a one-by-one reading. Pure code.

Usage: python3 offline.py      (N1.md, n1.json)
"""
from __future__ import annotations

import glob
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "scripts"))
from netzoo_agent_core.contracts.core_decision import FactQuestion  # noqa: E402
from netzoo_agent_core.interpretation.answered_doubts import answered_doubt  # noqa: E402

WT = Path("/Users/chenzhonghan/Documents/LLM AGENT/.worktrees")
ROOTS = [*glob.glob(str(WT / "netzoo-ct/docs/research-log/*/live/*/hb-*-1")),
         *glob.glob(str(WT / "netzoo-rr/docs/research-log/fresh-j10-2026-10-31/live/m*/hb-*-1")),
         *glob.glob(str(WT / "netzoo-ab/docs/research-log/answer-buttons-2026-10-31/live/*/hb-*-1")),
         *glob.glob(str(WT / "netzoo-ca/docs/research-log/count-answers-2026-10-31/live/ca-*"))]


def main():
    rows, seen = [], 0
    for session in sorted(ROOTS):
        for turn in sorted(Path(session).glob("t[0-9]"))[1:]:
            if not (turn / "session.json").exists():
                continue
            state = json.loads((turn / "session.json").read_text()).get("task_state")
            check = None
            for trace in sorted(turn.glob("trace-*.jsonl")):
                for line in trace.read_text().splitlines():
                    if '"core.fact_check"' in line and (event := json.loads(line))["event_type"] == "core.fact_check":
                        check = event["payload"]
            if not check or not state:
                continue
            for item in [*(check.get("accepted") or []), *(check.get("queued") or [])]:
                seen += 1
                question = FactQuestion.model_validate(item)
                fact = answered_doubt(question, state)
                if fact is not None:
                    rows.append({"session": session.split("/live/")[-1], "turn": turn.name,
                                 "question": question.question, "quote": question.user_quote,
                                 "answered": fact.question, "source": fact.source, "value": fact.value})
    (HERE / "n1.json").write_text(json.dumps(rows, indent=1))
    lines = ["# N1 (generated by offline.py; do not edit)", "",
             f"- later-turn fact-agent questions {seen}; blocked by an answered agent/count doubt {len(rows)}", ""]
    lines += [f"- {r['session']} {r['turn']}: \"{r['question']}\" -- blocked by {r['source']} \"{r['answered']}\" = "
              f"{r['value']} (words: \"{r['quote'][:90]}\")" for r in rows]
    (HERE / "N1.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
