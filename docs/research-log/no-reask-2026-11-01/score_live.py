"""no-reask live M1/M2 (ROUND.md) from live/. No model call.

M1 (hard): no turn asks a question whose user words an earlier turn's agent or count answer already settled (the
answers the app kept, bound before that turn). M2 (hard): no run ends worse than the count-answers run of the same
prompt and click (below: refused for the count; meets: not refused for it). Reps 1-2 pair with count-answers reps 1-2
(below); reps 3-4 with its rep 3 (meets).

Usage: python3 score_live.py      (LIVE.md)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "scripts"))
from netzoo_agent_core.interpretation.task_answers import _overlap  # noqa: E402

CA = HERE.parent / "count-answers-2026-10-31"
sys.path.insert(0, str(CA))
import score_live as CA_SCORE  # noqa: E402


def outcome(folder: Path) -> dict:
    turns = sorted(folder.glob("t[0-9]"))
    cores = [CA_SCORE.core_of(t) for t in turns]
    end = next((c for c in reversed(cores) if c), None) or {}
    lines = " ".join(part.get("line", "") for part in end.get("declined") or [])
    refused = end.get("kind") == "DECLINE" and (end.get("basis") == "count_answer" or bool(CA_SCORE.MINIMUM.search(lines)))
    reasked = []
    for index, (turn, core) in enumerate(zip(turns, cores)):
        if index == 0 or not core or core.get("kind") != "ASK":
            continue
        before = json.loads((turns[index - 1] / "session.json").read_text()).get("task_state") or {}
        answered = [f for f in before.get("facts") or [] if f.get("source") in ("agent", "count")
                    and f.get("status", "known") == "known"]
        if (turn / "session.json").exists():  # answers bound at the start of this turn count as answered too
            now = json.loads((turn / "session.json").read_text()).get("task_state") or {}
            answered += [f for f in now.get("facts") or [] if f.get("source") in ("agent", "count")
                         and f.get("turn") == index and f.get("status", "known") == "known"]
        for fact in core.get("facts") or []:
            if any(_overlap(fact.get("user_quote", ""), a.get("user_quote", "")) for a in answered):
                reasked.append(f"{turn.name}: {fact.get('question')}")
    return {"end": f"{end.get('kind')}/{end.get('basis')}", "refused": refused, "reasked": reasked}


def main():
    lines, m1, m2 = [], [], []
    for folder in sorted((HERE / "live").glob("nr-*")):
        job = json.loads((folder / "job.json").read_text())
        now = outcome(folder)
        ref_rep = job["rep"] if job["rep"] <= 2 else 3
        then = outcome(CA / "live" / f"ca-{job['prompt']}-{ref_rep}")
        good = (lambda o: o["refused"]) if job["mode"] == "below" else (lambda o: not o["refused"])
        if now["reasked"]:
            m1.append(folder.name)
        if good(then) and not good(now):
            m2.append(folder.name)
        lines.append(f"- {folder.name} {job['mode']}: sent {job['sent'][1:]} -> {now['end']} "
                     f"{'right' if good(now) else 'WRONG'} | re-asked {now['reasked']} | count-answers "
                     f"ca-{job['prompt']}-{ref_rep}: {then['end']} {'right' if good(then) else 'WRONG'} "
                     f"(re-asked {then['reasked']})")
    out = ["# no-reask live (generated by score_live.py; do not edit)", "",
           f"- M1 (hard) runs re-asking an answered doubt: {len(m1)} {m1}: {'pass' if not m1 else 'FAIL'}",
           f"- M2 (hard) runs ending worse than count-answers: {len(m2)} {m2}: {'pass' if not m2 else 'FAIL'}", "",
           *lines]
    (HERE / "LIVE.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
