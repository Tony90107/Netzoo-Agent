"""clarify-menu live L1/L2 (ROUND.md): cm1/cm2 against their recorded current-system runs (same item, typed
reply_result), each judged against the item's gold after what it sent. A conversation is "clicked" when a turn's
reply was the family button (the CLICKS.json rule fired on that turn's card). No model call.

Usage: python3 score_live.py      (LIVE.md)
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
import run_live as R  # noqa: E402

RECORDED = {**{f"h9r{r}": R.CT / f"hybrid-j9-2026-10-31/live/h9r{r}" for r in (1, 2)},
            **{f"m{r}": R.WORKTREES / "netzoo-rr/docs/research-log/fresh-j10-2026-10-31/live" / f"m{r}" for r in (1, 2)}}


def end_of(folder: Path):
    turns = sorted(folder.glob("t[0-9]"))
    core = next((c for c in (R.turn_core(t) for t in reversed(turns)) if c), None)
    sent = json.loads((folder / "job.json").read_text()).get("sent", [])
    kind = None if not core else ("PARTIAL" if core["kind"] == "DO" and core.get("partial") else core["kind"])
    return kind, sent, turns


def right(kind, item, sent) -> bool:
    gold = item["final_after_result"]["call"] if "result" in sent and item.get("final_after_result") else item["expected_call"]
    ok = {gold, *(item.get("also_acceptable") or [])} if gold == item["expected_call"] else {gold}
    fold = lambda c: "DO" if c == "PARTIAL" else c  # noqa: E731
    return kind is not None and fold(kind) in {fold(x) for x in ok}


def main():
    items = {i["id"]: i for path, _ in R.SETS for i in json.loads(path.read_text())["single"]}
    lines, worse, clicked, clicked_right = [], [], 0, 0
    for tag, picked in R.CLICKS["reps"].items():
        for item_id, rec in picked.items():
            item, folder = items[item_id], HERE / "live" / tag / f"hb-{tag}-{item_id}-1"
            then_kind, then_sent, _ = end_of(next(RECORDED[rec].glob(f"hb-*-{item_id}-1")))
            if not folder.exists():
                lines.append(f"- {tag} {item_id}: not run")
                continue
            kind, sent, turns = end_of(folder)
            click = any(R.clicked(item, R.turn_core(t) or {}, t) is not None for t in turns[:-1])
            ok_now, ok_then = right(kind, item, sent), right(then_kind, item, then_sent)
            clicked += click
            clicked_right += click and ok_now
            if ok_then and not ok_now:
                worse.append(f"{tag} {item_id}")
            lines.append(f"- {tag} {item_id} (recorded {rec}): now {kind} sent {sent} clicked {click} "
                         f"{'right' if ok_now else 'WRONG'} | recorded {then_kind} sent {then_sent} "
                         f"{'right' if ok_then else 'WRONG'}")
    out = ["# clarify-menu live (generated by score_live.py; do not edit)", "",
           f"- L1 (hard) ending worse than recorded: {len(worse)} {worse}: {'pass' if not worse else 'FAIL'}",
           f"- L2 (target) clicked conversations at the gold call: {clicked_right}/{clicked} (>= 70%): "
           f"{'pass' if clicked and clicked_right >= 0.7 * clicked else 'FAIL'}", "", *lines]
    (HERE / "LIVE.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
