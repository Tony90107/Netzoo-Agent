"""answer-buttons round 2, C1 (ROUND-2.md): every recorded ASK turn rendered through the card builder's `_core_card`
with the branch its recording used (read from the recorded card's headline) and the recorded decision (`session.json`
plan), flag on; every single closed question must show buttons, and each button's answer must bind exactly its option.
Pure code, no model call.

Usage: python3 offline2.py      (C1.md, c1.json)
"""
from __future__ import annotations

import glob
import json
import os
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
os.environ["NETZOO_ANSWER_BUTTONS"] = "on"

from evaluate_routing import ProjectPolicyLoader  # noqa: E402
from netzoo_agent_core.contracts import TaskDecision  # noqa: E402
from netzoo_agent_core.engine.answer_buttons import buttons  # noqa: E402
from netzoo_agent_core.contracts.task_state import TaskState  # noqa: E402
from netzoo_agent_core.engine.task_updates import after_turn, bind_answers  # noqa: E402
from netzoo_agent_core.reply_cards.builder import _core_card  # noqa: E402

import offline as B1  # noqa: E402  (the same runs)

POLICY = ProjectPolicyLoader(ROOT).load()
BRANCH = {"One fact decides your request; please tell me first.": "ask_facts",
          "One fact about your data decides which workflow applies.": "needs_fact"}


def main():
    rows, outcome = [], Counter()
    for run, folder in B1.RUNS.items():
        for turn in sorted(glob.glob(str(folder / "hb-*-1" / "t[0-9]"))):
            core = None
            for trace in sorted(glob.glob(turn + "/trace-*.jsonl")):
                for line in open(trace):
                    if '"core.decision"' in line and (event := json.loads(line))["event_type"] == "core.decision":
                        core = event["payload"]
            if not core or core.get("kind") != "ASK":
                continue
            cards = json.loads(Path(turn, "cards.json").read_text()) if Path(turn, "cards.json").exists() else []
            branch = next((BRANCH[c.get("headline")] for c in cards if c.get("headline") in BRANCH), None)
            # The state the app kept after the turn (session.json); the trace's copy of the core can list a question's
            # options in another order (first run of this check: 9 input_network turns, order only).
            session = json.loads(Path(turn, "session.json").read_text()) if Path(turn, "session.json").exists() else {}
            state = (TaskState.model_validate(session["task_state"]) if session.get("task_state")
                     else after_turn(None, {"decision": {"core": core}}, "request"))
            asked = [q for q in (state.pending if state else []) if q.status == "asked"]
            kind = B1.kind_of(asked[0].what, asked[0].source) if asked else "none asked"
            expected = buttons(asked[0]) if len(asked) == 1 else []
            if branch is None:
                status, shown = "other card", []
            else:
                decision = TaskDecision.model_validate(session["plan"]["decision"])
                card = _core_card(branch, decision, POLICY, session["messages"][-2]["content"]
                                  if len(session.get("messages", [])) >= 2 else "")
                shown = [(o.label, o.answer) for o in (card.choices.options if card and card.choices else [])]
                ok = [(label, answer) for _v, label, answer in expected] == shown
                for value, _label, answer in expected:
                    _after, bound, _ = bind_answers(state, answer)
                    ok = ok and len(bound) == 1 and bound[0].value == value
                status = "no closed answers" if not expected else ("pass" if ok else "FAIL")
            outcome[(branch or "other card", kind, status)] += 1
            rows.append({"run": run, "turn": turn.split("/live/")[-1], "branch": branch, "kind": kind,
                         "status": status, "shown": shown})
    (HERE / "c1.json").write_text(json.dumps(rows, indent=1))
    failed = [r for r in rows if r["status"] == "FAIL"]
    lines = ["# C1 real-card round trip (generated by offline2.py; do not edit)", "",
             "Second run: the task state is the one the app kept (session.json); the first run built it from the "
             "trace's copy of the core and failed 9 input_network turns on option order only (see RESULTS-2.md).", "",
             f"- recorded ASK turns {len(rows)}; rendered with buttons and round-tripped "
             f"{sum(r['status'] == 'pass' for r in rows)}; failed {len(failed)}: {'pass' if not failed else 'FAIL'}",
             "", "| card | kind | status | turns |", "|---|---|---|---|"]
    lines += [f"| {b} | {k} | {s} | {n} |" for (b, k, s), n in sorted(outcome.items())]
    lines += ["", "Failures:"] + [f"- {r['run']} {r['turn']} {r['branch']} {r['kind']}: shown {r['shown']}"
                                  for r in failed]
    (HERE / "C1.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
