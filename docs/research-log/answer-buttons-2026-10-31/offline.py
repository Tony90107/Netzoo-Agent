from netzoo_agent_core.contracts.core_decision import CoreDecision  # noqa: E402
from netzoo_agent_core.engine.answer_buttons import buttons  # noqa: E402
from netzoo_agent_core.engine.task_updates import after_turn, bind_answers  # noqa: E402
from netzoo_agent_core.reply_cards.answer_buttons import ask_choices  # noqa: E402

CT = Path("/Users/chenzhonghan/Documents/LLM AGENT/.worktrees/netzoo-ct/docs/research-log")
RR = Path("/Users/chenzhonghan/Documents/LLM AGENT/.worktrees/netzoo-rr/docs/research-log")
RUNS = {"j1": CT / "jev-guard-2026-10-27/live/j1", "j2": CT / "jev-guard-2026-10-27/live/j2g",
        "j3": CT / "jev-j3-2026-10-27/live/j3g", "j4": CT / "jev-j4-2026-10-27/live/j4g",
        "j5": CT / "jev-j5-2026-10-28/live/j5a", "j6": CT / "jev-j6-2026-10-29/live/j6a",
        "j7": CT / "jev-links-first-2026-10-29/live/j7off", "j8": CT / "j8-paired-2026-10-29/live/j8new",
        "j9r1": CT / "hybrid-j9-2026-10-31/live/h9r1", "j9r2": CT / "hybrid-j9-2026-10-31/live/h9r2",
        "j9r3": CT / "hybrid-j9-2026-10-31/live/h9r3", "j10r1": RR / "fresh-j10-2026-10-31/live/m1",
        "j10r2": RR / "fresh-j10-2026-10-31/live/m2", "j10r3": RR / "fresh-j10-2026-10-31/live/m3"}


def kind_of(what: str, source: str) -> str:
    if what.startswith("jev_link:"):
        return "jev_link"
    if what.startswith("jev:"):
        return what
    if source == "agent":
        return "agent"
    return "setting" if "." in what else what or source


def main():
    rows, outcome = [], Counter()
    for run, folder in RUNS.items():
        for turn in sorted(glob.glob(str(folder / "hb-*-1" / "t[0-9]"))):
            core = None
            for trace in sorted(glob.glob(turn + "/trace-*.jsonl")):
                for line in open(trace):
                    if '"core.decision"' in line and (event := json.loads(line))["event_type"] == "core.decision":
                        core = event["payload"]
            if not core or core.get("kind") != "ASK":
                continue
            model = CoreDecision.model_validate({k: v for k, v in core.items() if k in CoreDecision.model_fields})
            state = after_turn(None, {"decision": {"core": core}}, "request")
            asked = [q for q in (state.pending if state else []) if q.status == "asked"]
            kind = kind_of(asked[0].what, asked[0].source) if asked else "none asked"
            choices = ask_choices(model)
            shown = [(o.label, o.answer) for o in choices.options] if choices else []
            expected = buttons(asked[0]) if len(asked) == 1 else []
            ok, detail = True, []
            if [(label, answer) for _v, label, answer in expected] != shown:
                ok = False
                detail.append("card differs from the binder's buttons")
            for value, _label, answer in expected:
                _after, bound, _corrected = bind_answers(state, answer)
                if len(bound) != 1 or bound[0].value != value or bound[0].question_id != asked[0].question_id:
                    ok = False
                    detail.append(f"{answer!r} bound {[b.value for b in bound]}")
            status = "no buttons" if not expected else ("pass" if ok else "FAIL")
            outcome[(kind, status)] += 1
            rows.append({"run": run, "turn": turn.split("/live/")[-1], "kind": kind, "status": status,
                         "question": asked[0].question[:160] if asked else "", "buttons": shown, "detail": detail})
    (HERE / "b1.json").write_text(json.dumps(rows, indent=1))
    with_buttons = [r for r in rows if r["status"] != "no buttons"]
    failed = [r for r in rows if r["status"] == "FAIL"]
    lines = ["# B1 round trip (generated by offline.py; do not edit)", "",
             f"- recorded ASK turns {len(rows)}; with buttons {len(with_buttons)}; round trip failed {len(failed)}: "
             f"{'pass' if not failed else 'FAIL'}", "", "| kind | pass | FAIL | no buttons |", "|---|---|---|---|"]
    for kind in sorted({k for k, _s in outcome}):
        lines.append(f"| {kind} | {outcome[(kind, 'pass')]} | {outcome[(kind, 'FAIL')]} | {outcome[(kind, 'no buttons')]} |")
    lines += ["", "Failures:"] + [f"- {r['run']} {r['turn']} {r['kind']}: {r['detail']}" for r in failed]
    lines += ["", "No buttons:"] + [f"- {r['run']} {r['turn']} {r['kind']}: {r['question']}"
                                    for r in rows if r["status"] == "no buttons"][:40]
    (HERE / "B1.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
