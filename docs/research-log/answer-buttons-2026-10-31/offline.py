"""answer-buttons B1 (ROUND.md): every recorded ASK turn of the current-system runs (j1-j8, j9 r1-r3, j10 arm M
r1-r3). For each: the card's buttons from this checkout's code (flag on), the task state after the turn
(`after_turn`, as the app keeps it), then each button's answer sent as the reply (`bind_answers`) -- it must bind
exactly the option the button shows. Pure code, no model call.

Usage: python3 offline.py      (B1.md, b1.json)
"""
