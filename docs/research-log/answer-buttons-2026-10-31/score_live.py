"""answer-buttons live L1/L2 (ROUND.md): each rerun conversation against its recorded current-system run, each judged
against the item's gold after what it sent (a `fact` click or reply -> final_after_fact). No model call.

Usage: python3 score_live.py      (LIVE.md)
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
import run_live as R  # noqa: E402

RECORDED = {"h9r1": R.CT / "hybrid-j9-2026-10-31/live/h9r1", "h9r2": R.CT / "hybrid-j9-2026-10-31/live/h9r2",
            "h9r3": R.CT / "hybrid-j9-2026-10-31/live/h9r3", "m1": R.RR / "fresh-j10-2026-10-31/live/m1",
            "m2": R.RR / "fresh-j10-2026-10-31/live/m2", "m3": R.RR / "fresh-j10-2026-10-31/live/m3"}


def end_of(folder: Path):
    turns = sorted(folder.glob("t[0-9]"))
    core = R.turn_core(turns[-1]) if turns else None
    sent = json.loads((folder / "job.json").read_text()).get("sent", [])
    kind = None if not core else ("PARTIAL" if core["kind"] == "DO" and core.get("partial") else core["kind"])
    return kind, sent


def right(kind, item, sent) -> bool:
    gold = item["final_after_fact"]["call"] if "fact" in sent and item.get("final_after_fact") else item["expected_call"]
    ok = {gold, *(item.get("also_acceptable") or [])} if gold == item["expected_call"] else {gold}
    fold = lambda c: "DO" if c == "PARTIAL" else c  # noqa: E731
    return kind is not None and fold(kind) in {fold(x) for x in ok}


def main():
    items = {i["id"]: i for path, _ in R.SETS for i in json.loads(path.read_text())["single"]}
    lines, now_right, worse = [], 0, []
    total = 0
    for tag, picked in R.CLICKS["reps"].items():
        for item_id, rec in picked.items():
            item, total = items[item_id], total + 1
            folder = HERE / "live" / tag / f"hb-{tag}-{item_id}-1"
            then_kind, then_sent = end_of(next(RECORDED[rec].glob(f"hb-*-{item_id}-1")))
            if not folder.exists():
                lines.append(f"- {tag} {item_id}: not run")
                continue
            kind, sent = end_of(folder)
            ok_now, ok_then = right(kind, item, sent), right(then_kind, item, then_sent)
            now_right += ok_now
            if ok_then and not ok_now:
                worse.append(f"{tag} {item_id}")
            lines.append(f"- {tag} {item_id} (recorded {rec}): now {kind} sent {sent} {'right' if ok_now else 'WRONG'} | "
                         f"recorded {then_kind} sent {then_sent} {'right' if ok_then else 'WRONG'}")
    out = ["# answer-buttons live (generated by score_live.py; do not edit)", "",
           f"- L1 (hard) conversations ending worse than recorded: {len(worse)} {worse}: "
           f"{'pass' if not worse else 'FAIL'}",
           f"- L2 (target) ending at the gold call: {now_right}/{total} (>= 70%): "
           f"{'pass' if now_right >= 0.7 * total else 'FAIL'}", "", *lines]
    (HERE / "LIVE.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
