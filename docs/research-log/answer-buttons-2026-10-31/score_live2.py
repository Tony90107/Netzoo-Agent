"""answer-buttons round 2 live D1/D2 (ROUND-2.md): tags ac1-ac3 against their recorded current-system runs. A
conversation counts for D2 when some turn's reply was a click (the CLICKS.json rule fired on that turn's card). No
model call.

Usage: python3 score_live2.py      (LIVE-2.md)
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
import run_live as R  # noqa: E402
from score_live import RECORDED, end_of, right  # noqa: E402


def clicked_turns(item: dict, folder: Path) -> int:
    turns = sorted(folder.glob("t[0-9]"))
    return sum(R.clicked(item, R.turn_core(turn) or {}, turn) is not None for turn in turns[:-1])


def main():
    items = {i["id"]: i for path, _ in R.SETS for i in json.loads(path.read_text())["single"]}
    lines, worse, clicked, clicked_right = [], [], 0, 0
    for tag in ("ac1", "ac2", "ac3"):
        for item_id, rec in R.CLICKS["reps"][tag].items():
            item, folder = items[item_id], HERE / "live" / tag / f"hb-{tag}-{item_id}-1"
            then_kind, then_sent = end_of(next(RECORDED[rec].glob(f"hb-*-{item_id}-1")))
            if not folder.exists():
                lines.append(f"- {tag} {item_id}: not run")
                continue
            kind, sent = end_of(folder)
            ok_now, ok_then = right(kind, item, sent), right(then_kind, item, then_sent)
            clicks = clicked_turns(item, folder)
            if clicks:
                clicked += 1
                clicked_right += ok_now
            if ok_then and not ok_now:
                worse.append(f"{tag} {item_id}")
            lines.append(f"- {tag} {item_id} (recorded {rec}): now {kind} sent {sent} clicks {clicks} "
                         f"{'right' if ok_now else 'WRONG'} | recorded {then_kind} {'right' if ok_then else 'WRONG'}")
    out = ["# answer-buttons round 2 live (generated by score_live2.py; do not edit)", "",
           f"- D1 (hard) ending worse than recorded: {len(worse)} {worse}: {'pass' if not worse else 'FAIL'}",
           f"- D2 (target) clicked conversations at the gold call: {clicked_right}/{clicked} (>= 70%): "
           f"{'pass' if clicked and clicked_right >= 0.7 * clicked else 'FAIL'}", "", *lines]
    (HERE / "LIVE-2.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
